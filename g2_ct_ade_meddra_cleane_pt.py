"""Remove rows containing excluded PT codes from the g1 MedDRA output.

Run: python g2_create_ct_ade_meddra_cleaned.py
Defaults are relative to this script, so it can run from any directory.
All pt_code values in the exclusion CSV are used, regardless of priority.
"""

import argparse
import csv
from pathlib import Path
from tempfile import NamedTemporaryFile


ROOT = Path(__file__).resolve().parent


def load_excluded_codes(path: Path) -> set[str]:
    """Read the complete exclusion list, accepting a UTF-8 BOM."""
    with path.open(encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        if not reader.fieldnames or "pt_code" not in reader.fieldnames:
            raise ValueError(f"{path}: missing required column 'pt_code'")
        return {row["pt_code"].strip() for row in reader if row["pt_code"].strip()}


def clean_ct_ade(input_path: Path, excluded_path: Path, output_path: Path) -> dict[str, int]:
    """Stream records, preserving column order, retained row order and cell values.

    Match whole PT codes, splitting multiple mappings on '|'. A match removes
    the entire record. Missing PT codes are retained. Publish the output only
    after the full input has been processed successfully.
    """
    if output_path.resolve() in {input_path.resolve(), excluded_path.resolve()}:
        raise ValueError("Output must differ from both input files")
    csv.field_size_limit(100_000_000)
    excluded_codes = load_excluded_codes(excluded_path)
    counts = {"excluded_codes": len(excluded_codes), "input_rows": 0,
              "removed_rows": 0, "kept_rows": 0}
    temporary_path = None

    try:
        with input_path.open(encoding="utf-8-sig", newline="") as source:
            reader = csv.reader(source, strict=True)
            header = next(reader, [])
            if "ade_mapped_code_PT" not in header:
                raise ValueError(f"{input_path}: missing required column 'ade_mapped_code_PT'")
            pt_index = header.index("ade_mapped_code_PT")
            output_path.parent.mkdir(parents=True, exist_ok=True)
            with NamedTemporaryFile(mode="w", encoding="utf-8", newline="",
                                    dir=output_path.parent, prefix=f".{output_path.name}.",
                                    suffix=".tmp", delete=False) as destination:
                temporary_path = Path(destination.name)
                writer = csv.writer(destination, lineterminator="\n")
                writer.writerow(header)
                for row in reader:
                    if not row:
                        continue
                    counts["input_rows"] += 1
                    if len(row) != len(header):
                        raise ValueError(
                            f"{input_path}: record {counts['input_rows']}: "
                            f"expected {len(header)} columns, got {len(row)}"
                        )
                    if any(code.strip() in excluded_codes for code in row[pt_index].split("|")):
                        counts["removed_rows"] += 1
                    else:
                        writer.writerow(row)
                        counts["kept_rows"] += 1
                    if counts["input_rows"] % 100_000 == 0:
                        print(f"Read {counts['input_rows']:,} rows; "
                              f"removed {counts['removed_rows']:,} rows", flush=True)
        temporary_path.replace(output_path)
    finally:
        if temporary_path is not None:
            temporary_path.unlink(missing_ok=True)

    return counts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path,
                        default=ROOT / "data/ct_ade/ct_ade_meddra.csv",
                        help="Input CSV generated by g1")
    parser.add_argument("--excluded", type=Path,
                        default=ROOT / "data/excluded_pt/pt_excluded.csv",
                        help="Exclusion CSV containing pt_code")
    parser.add_argument("--output", type=Path,
                        default=ROOT / "data/ct_ade/ct_ade_meddra_cleaned.csv",
                        help="Cleaned output CSV")
    args = parser.parse_args()
    print(f"Input: {args.input}\nExclusion list: {args.excluded}", flush=True)
    counts = clean_ct_ade(args.input, args.excluded, args.output)
    print(f"Excluded PT codes: {counts['excluded_codes']:,}")
    print(f"Input: {counts['input_rows']:,} rows; removed: {counts['removed_rows']:,} rows; "
          f"retained: {counts['kept_rows']:,} rows")
    print(f"Output saved to: {args.output.resolve()}")


if __name__ == "__main__":
    main()
